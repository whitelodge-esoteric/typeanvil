//! Agent authoring guide (CORE-579).
//!
//! The prose lives in `guide/authoring.md`. The capability lists and the
//! "avoid" table are GENERATED from the capability manifest
//! (`capabilities::manifest`), so the guide cannot drift from the engine.
//! Three published forms share this one body: the docs page, the agent skill
//! file, and the MCP prompt/resource. A test (`tests/it/authoring_guide.rs`)
//! fails when a committed form differs from the generated one.
//!
//! Spec: `docs/specifications/agent-authoring-guide.spec.md`.

use std::fmt::Write as _;

use crate::capabilities::{manifest, Capability, Status, SCHEMA};

const TEMPLATE: &str = include_str!("guide/authoring.md");

/// Repo paths of the committed forms, relative to the repository root.
pub const DOCS_PAGE_PATH: &str = "docs/guides/agent-authoring.md";
pub const SKILL_PATH: &str = "skills/typeanvil-authoring/SKILL.md";

/// Name of the MCP prompt, and URI of the MCP resource.
pub const PROMPT_NAME: &str = "write_document";
pub const RESOURCE_URI: &str = "typeanvil://guide/authoring";

fn names(entries: &[Capability], kind: &str, status: Status) -> Vec<String> {
    entries
        .iter()
        .filter(|c| c.kind == kind && c.status == status)
        .map(|c| format!("`{}`", c.name))
        .collect()
}

fn list(out: &mut String, title: &str, items: Vec<String>) {
    if items.is_empty() {
        return;
    }
    let _ = writeln!(out, "**{title}:** {}\n", items.join(", "));
}

fn generated_lists(entries: &[Capability]) -> String {
    let mut out = String::new();
    list(&mut out, "Supported CSS properties", names(entries, "property", Status::Supported));
    list(&mut out, "`@page` descriptors", names(entries, "page-descriptor", Status::Supported));
    list(&mut out, "Supported at-rules", names(entries, "at-rule", Status::Supported));
    list(&mut out, "Selectors", names(entries, "selector", Status::Supported));
    list(&mut out, "Input formats", names(entries, "input-format", Status::Supported));
    let partial: Vec<String> = entries
        .iter()
        .filter(|c| c.status == Status::Partial)
        .map(|c| format!("`{}:{}` ({})", c.kind, c.name, c.note))
        .collect();
    list(&mut out, "Partial support", partial);
    out.trim_end().to_string()
}

fn avoid_table(entries: &[Capability]) -> String {
    let mut out = String::from("| Do not use | Why | Use instead |\n|---|---|---|\n");
    for c in entries.iter().filter(|c| c.status == Status::Unsupported) {
        let label = match c.kind {
            "at-rule" => format!("`@{}`", c.name),
            _ => format!("`{}`", c.name),
        };
        let alt = c.alternative.unwrap_or("remove it");
        let _ = writeln!(out, "| {label} | {} | {alt} |", c.note);
    }
    out.trim_end().to_string()
}

/// The guide body (Markdown, no frontmatter), generated from the manifest.
pub fn body() -> String {
    let entries = manifest();
    TEMPLATE
        .replace("{{SCHEMA}}", &SCHEMA.to_string())
        .replace("{{GENERATED}}", &generated_lists(&entries))
        .replace("{{AVOID}}", &avoid_table(&entries))
}

/// The docs-site page: frontmatter plus the body.
pub fn docs_page() -> String {
    format!(
        "---\ntitle: Agent authoring guide\ntype: guide\nstatus: approved\nowner: maintainers\n\
created: 2026-10-25\nupdated: 2026-10-25\nsidebar_position: 9\n\
tags: [guide, ai-native, agents, authoring]\nslug: /guides/agent-authoring\n---\n\n\
{{/* GENERATED by `cargo test --test it authoring_guide` with UPDATE_GUIDE=1. Do not edit. */}}\n\n{}",
        body()
    )
}

/// The agent skill file (`SKILL.md` shape): frontmatter plus the body.
pub fn skill_file() -> String {
    format!(
        "---\nname: typeanvil-authoring\n\
description: \"Use when writing HTML or Markdown to render as a PDF with TypeAnvil. Lists supported CSS, paged-media idioms and how to fix render-report findings.\"\n\
version: 1.0.0\n---\n\n\
<!-- GENERATED by `cargo test --test it authoring_guide` with UPDATE_GUIDE=1. Do not edit. -->\n\n{}",
        body()
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn placeholders_are_all_replaced() {
        let b = body();
        assert!(!b.contains("{{"), "unreplaced placeholder");
        assert!(b.contains("`color`"));
        assert!(b.contains("`border-radius`"));
    }
}
